let currentQuestionIndex = 0;
let score = 0;
let timerInterval;
let timeLeft = 3600; // ???? ????? (????????)
let shuffledQuestions = [];

function startQuiz() {
  document.getElementById('start-screen').classList.add('hidden');
  document.getElementById('quiz-screen').classList.remove('hidden');
  
  // ??? ??????? ???????? ?? ????? ???????? ??? ????
  shuffledQuestions = JSON.parse(JSON.stringify(questionsData))
    .sort(() => Math.random() - 0.5);

  currentQuestionIndex = 0;
  score = 0;
  timeLeft = 3600;

  startTimer();
  loadQuestion();
}

function startTimer() {
  clearInterval(timerInterval);
  timerInterval = setInterval(() => {
    if (timeLeft <= 0) {
      clearInterval(timerInterval);
      endQuiz();
    } else {
      timeLeft--;
      let minutes = Math.floor(timeLeft / 60);
      let seconds = timeLeft % 60;
      document.getElementById('timer').innerText = `????? ???????: ${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
    }
  }, 1000);
}

function loadQuestion() {
  if (currentQuestionIndex >= shuffledQuestions.length) {
    endQuiz();
    return;
  }

  const qData = shuffledQuestions[currentQuestionIndex];
  document.getElementById('question-counter').innerText = `??????: ${currentQuestionIndex + 1} / ${shuffledQuestions.length}`;
  document.getElementById('question-text').innerText = `${currentQuestionIndex + 1}. ${qData.q}`;

  const optionsContainer = document.getElementById('options-container');
  optionsContainer.innerHTML = '';

  // ????? ???????? ?? ??? ???? ??????? ??????? ??????? ?????? ????????
  let optionsWithIndex = qData.options.map((opt, idx) => ({ text: opt, originalIndex: idx }));
  optionsWithIndex.sort(() => Math.random() - 0.5);

  optionsWithIndex.forEach((optObj) => {
    const btn = document.createElement('button');
    btn.innerText = optObj.text;
    btn.onclick = () => selectAnswer(btn, optObj.originalIndex === qData.answer);
    optionsContainer.appendChild(btn);
  });
}

function selectAnswer(selectedBtn, isCorrect) {
  // ????? ???? ??????? ?? ??? ?????? ???? ???????
  const buttons = document.querySelectorAll('.options-list button');
  buttons.forEach(b => b.disabled = true);

  // ????? ?? ???? ?????? ??????? ???????? ?????? ??????? ?????? ???????
  buttons.forEach(b => {
    // ???? ??????? ??????? ????? ??? ???? ?? ????? ??????
    const qData = shuffledQuestions[currentQuestionIndex];
    let originalOptText = qData.options[qData.answer];
    if (b.innerText === originalOptText) {
      b.classList.add('correct');
    }
  });

  if (isCorrect) {
    score++;
    selectedBtn.classList.add('correct');
  } else {
    selectedBtn.classList.add('wrong');
  }

  // ???????? ???????? ?????? ?????? ??? ????? ?????
  setTimeout(() => {
    currentQuestionIndex++;
    loadQuestion();
  }, 1200);
}

function endQuiz() {
  clearInterval(timerInterval);
  document.getElementById('quiz-screen').classList.add('hidden');
  document.getElementById('result-screen').classList.remove('hidden');
  document.getElementById('score-display').innerText = `${score} / ${shuffledQuestions.length}`;
}

function restartQuiz() {
  document.getElementById('result-screen').classList.add('hidden');
  startQuiz();
}